/**
 * Returns a deep-cloned, shuffled copy of the player pool
 * (prevents mutation of the source array between rooms).
 */
export const getShuffledPlayerPool = (poolSize: number = 60): Player[] => {
  const pool = PLAYERS.slice(0, Math.min(poolSize, PLAYERS.length)).map((p) => ({
    ...p,
    isSold: false,
    soldTo: null,
    soldPrice: null,
  }));
  // Fisher-Yates shuffle
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool;
};
